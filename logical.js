let marks = 82;
let isAdult = false;

/* 
logical and --> &&
only will be true if both condition is true.
*/

console.log(marks>=80 && isAdult === true);

/* 
LOGICAL OR --> ||
will be true if any of the condition is true.
*/

console.log(marks>=80 || isAdult === true);

// LOGICAL NOT --> ! flips the value

console.log(!isAdult);


