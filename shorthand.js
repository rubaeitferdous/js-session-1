//decremental operators
let age = 20;
console.log(age);
age--
console.log(age);
age--
console.log(age);
age--
console.log(age);
age--
console.log(age);

//incremental shorthand
age += 10;
console.log(age);
age += 5;
console.log(age);

//decremental shorthand
age -= 7;
console.log(age);

